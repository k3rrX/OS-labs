=== РАСЧЕТ УСКОРЕНИЯ И ЭФФЕКТИВНОСТИ ===

1. ДЛЯ 100,000 ЭЛЕМЕНТОВ:
   - 1 поток:   0.031 сек
   - 2 потока:  0.020 сек  → Ускорение: 0.031 / 0.020 = 1.55x
   - 4 потока:  0.005 сек  → Ускорение: 0.031 / 0.005 = 6.20x (СУПЕРЛИНЕЙНОЕ!)
   - 8 потоков: 0.018 сек  → Ускорение: 0.031 / 0.018 = 1.72x

2. ДЛЯ 500,000 ЭЛЕМЕНТОВ:
   - 1 поток:   0.071 сек
   - 2 потока:  0.075 сек  → Ускорение: 0.071 / 0.075 = 0.94x (замедление)
   - 4 потока:  0.051 сек  → Ускорение: 0.071 / 0.051 = 1.39x
   - 8 потоков: 0.030 сек  → Ускорение: 0.071 / 0.030 = 2.36x

3. ДЛЯ 1,000,000 ЭЛЕМЕНТОВ:
   - 1 поток:   0.135 сек
   - 2 потока:  0.124 сек  → Ускорение: 0.135 / 0.124 = 1.08x
   - 4 потока:  0.058 сек  → Ускорение: 0.135 / 0.058 = 2.32x
   - 8 потоков: 0.066 сек  → Ускорение: 0.135 / 0.066 = 2.04x

=== ОБЪЯСНЕНИЕ РЕЗУЛЬТАТОВ ===

1. СУПЕРЛИНЕЙНОЕ УСКОРЕНИЕ (6.20x на 100k):
   - Каждый поток работает с меньшим объемом данных (25k элементов)
   - Данные помещаются в кэш процессора L2/L3
   - Уменьшаются промахи кэша и обращения к RAM
   - Эффект "скрытого параллелизма" в современных CPU

2. НАИЛУЧШИЕ РЕЗУЛЬТАТЫ ПРИ 4 ПОТОКАХ:
   - Система имеет 8 ядер, но 4 потока оптимальны
   - Причина: накладные расходы на создание потоков и слияние
   - Гипертрейдинг дает меньший выигрыш чем реальные ядра

3. ЗАМЕДЛЕНИЕ ПРИ 2 ПОТОКАХ НА 500k:
   - На маленьких задачах накладные расходы превышают выгоду
   - Неравномерное распределение нагрузки
   - Конкуренция за доступ к памяти

=== РЕКОМЕНДАЦИИ ПО ИСПОЛЬЗОВАНИЮ ===

1. Для массивов < 50,000: использовать 1 поток
2. Для массивов 50,000 - 200,000: использовать 2-4 потока  
3. Для массивов > 200,000: использовать 4 потока
4. Максимум 8 потоков только для массивов > 1,000,000

=== КОМАНДЫ ДЛЯ ДЕМОНСТРАЦИИ ===
1. Проверить потоки системы:  ./timsort -i
2. Тест на 100k:             ./timsort -n 100000 -t 4 -c -p 5
3. Сравнить режимы:          for t in 1 2 4 8; do echo -n "\$t потоков: "; ./timsort -n 500000 -t \$t 2>/dev/null | grep "Время"; done
EOF
